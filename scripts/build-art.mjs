// Generates packages/ui/src/art.ts from design/design-system/components/bundle.js,
// so the gang, The Hug, icons and doodles stay exactly as designed.
// React Native can't render SVG filters, so the crayon-grain filters are left out.
// Run: npm run art
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const bundle = readFileSync(`${root}design/design-system/components/bundle.js`, 'utf8');

function literal(name) {
  const start = bundle.indexOf(`var ${name} = `);
  if (start < 0) throw new Error(`${name} not found in bundle.js`);
  const from = start + `var ${name} = `.length;
  let depth = 0;
  for (let i = from; i < bundle.length; i++) {
    if (bundle[i] === '{') depth++;
    if (bundle[i] === '}' && --depth === 0) return new Function(`return ${bundle.slice(from, i + 1)}`)();
  }
  throw new Error(`${name} has no end`);
}

const D = literal('D');
const DOODLES = literal('DOODLES');
const DOODLE_INK = literal('DOODLE_INK');

const clean = (svg, id) =>
  svg
    .replace(/ filter="url\(#__[FR]__\)"/g, '')
    .split('__CLIP__').join(`ts-clip-${id}`)
    .replace(/ class="[^"]*"/g, '');

const DUTCH = { bo: 'Bo de beer', tiggy: 'Tiggy de tijger', bizzy: 'Bizzy de bij', puddle: 'Puddle de eend' };

const characters = {};
for (const [id, c] of Object.entries(D.chars)) {
  const poses = {};
  for (const mood of ['default', 'happy', 'still']) if (c[mood]) poses[mood] = clean(c[mood], id);
  characters[id] = { name: DUTCH[id], motion: c.motion, poses };
}

const doodles = {};
for (const [id, [viewBox, svg]] of Object.entries(DOODLES)) doodles[id] = { viewBox, svg: clean(svg, id), ink: DOODLE_INK[id] };

const out = `// Generated by scripts/build-art.mjs from design/design-system/components/bundle.js. Do not edit.
// SVG markup per character pose, icon and doodle. Doodle markup uses "C" as the colour placeholder.
export const characters = ${JSON.stringify(characters, null, 2)} as const;

export const hug = ${JSON.stringify(clean(D.hug, 'hug'))};

export const icons = ${JSON.stringify(D.icons, null, 2)} as const;

export const doodles = ${JSON.stringify(doodles, null, 2)} as const;
`;

writeFileSync(`${root}packages/ui/src/art.ts`, out);
console.log('Wrote packages/ui/src/art.ts');
